def build(spf_m, spf_d, spf_a, hc_w, hc_d, hc_a, direction):
    if direction == "-1":
        return f"{spf_m},{spf_d},{spf_a}", f"{hc_w},{hc_d},{hc_a}"
    else:  # +1 -> 客队让-1 视角
        return f"{spf_a},{spf_d},{spf_m}", f"{hc_a},{hc_d},{hc_w}"

fails = []
for name, d, sm, sd, sa, hw, hd, ha in matches:
    spf, hc = build(sm, sd, sa, hw, hd, ha, d)
    r = subprocess.run([sys.executable, ODDS_CHECK, "--spf", spf, "--handicap", hc],
                      capture_output=True, text=True)
    ok = r.returncode == 0
    print(f"\n===== {name} (让球{d}) =====")
    print(r.stdout.strip())
    if not ok:
        fails.append(name)

print("\n\n================ 汇总 ================")
print(f"总计 {len(matches)} 场，失败 {len(fails)} 场")
if fails:
    print("❌ 失败场次：")
    for f in fails:
        print("  -", f)
    sys.exit(1)
else:
    print("✅ 全部通过机器校验，可入库")
    sys.exit(0)
